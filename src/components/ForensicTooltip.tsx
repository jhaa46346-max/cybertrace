import React, { useState } from 'react';
import { HelpCircle } from 'lucide-react';

interface ForensicTooltipProps {
  term: string;
  explanation: string;
  children?: React.ReactNode;
}

export const FORENSIC_GLOSSARY: Record<string, string> = {
  log: 'Computer Activity Record: A chronological text trace generated by operating systems or web servers.',
  sha256: 'Digital Fingerprint: A 64-character cryptographic hash. If even a single space is modified, the entire fingerprint changes.',
  skew: 'Clock Skew: Time drift (in seconds) between a computer\'s internal clock and true real-world UTC time.',
  rfc3164: 'RFC 3164 Syslog: Traditional Linux log format that omits the year and timezone, requiring automated inference.',
  custody: 'Chain of Custody: A tamper-evident cryptographic ledger where each record is mathematically linked to the previous record.',
  inferred: 'Inferred Timestamp: The year or timezone was deduced using the case reference date and server location.',
  exact: 'Exact Timestamp: Both the year and timezone were explicitly recorded inside the log line itself.',
  unparsed: 'Unparsed Line: Malformed or non-conforming text preserved untouched so zero forensic evidence is dropped.',
  privEsc: 'Privilege Escalation: When a standard user gains administrative (root/sudo) access to the system.',
};

export const ForensicTooltip: React.FC<ForensicTooltipProps> = ({
  term,
  explanation,
  children,
}) => {
  const [isVisible, setIsVisible] = useState(false);

  return (
    <span
      className="relative inline-flex items-center gap-1 group cursor-help"
      onMouseEnter={() => setIsVisible(true)}
      onMouseLeave={() => setIsVisible(false)}
      onFocus={() => setIsVisible(true)}
      onBlur={() => setIsVisible(false)}
      tabIndex={0}
    >
      {children ? (
        <span>{children}</span>
      ) : (
        <span className="border-b border-dotted border-slate-500">{term}</span>
      )}
      <HelpCircle className="w-3 h-3 text-slate-500 hover:text-sky-400 shrink-0 transition-colors" />

      {isVisible && (
        <span
          role="tooltip"
          className="absolute bottom-full left-1/2 -translate-x-1/2 mb-1.5 w-64 p-2 bg-slate-900 border border-slate-700 rounded-md text-[11px] text-slate-200 shadow-xl z-50 pointer-events-none leading-relaxed"
        >
          <strong className="block text-sky-400 mb-0.5">{term}</strong>
          {explanation}
        </span>
      )}
    </span>
  );
};
